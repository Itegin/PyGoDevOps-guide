    conn.execute(
        "INSERT INTO metrics (ts, cpu, ram, disk) VALUES (?, ?, ?, ?)",
        (datetime.now(timezone.utc).isoformat(), system["cpu"], system["ram"], system["disk"]),
    )
    conn.commit()

